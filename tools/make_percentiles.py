"""Sample random charts and emit the score quantile table + per-dimension stats.

    python tools/make_percentiles.py [N]

A 0-100 "structure score" has no absolute meaning. This script turns it into a
percentile by sampling random charts, so the app can say "top X %" instead of
pretending 70/100 means something on its own.
"""
import os
import random
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from mingli.bazi.chart import build_chart          # noqa: E402
from mingli.ziwei.chart import build_ziwei         # noqa: E402
from mingli.bazi.luck import timeline              # noqa: E402
from mingli import scoring                          # noqa: E402


def sample(n=2000, seed=20261018):
    random.seed(seed)
    vals, dims, years = [], [], []
    for _ in range(n):
        y = random.randint(1905, 2030)
        m = random.randint(1, 12)
        d = random.randint(1, 28)
        h = random.randint(0, 23)
        mi = random.randint(0, 59)
        g = random.choice(["male", "female"])
        lon = round(random.uniform(87, 126), 2)
        c = build_chart("s", g, y, m, d, h, mi, longitude=lon)
        z = build_ziwei("s", g, y, m, d, h, mi, longitude=lon)
        s = scoring.score_overall(c, z)
        vals.append(s["overall"])
        dims.append(s["dimensions"])
        # 流年分数也要有自己的分布：32-94 是人为限的，没有分位数就还是「分数」，
        # 不是「位置」。起始年随机，避免所有人都在同一条大运上采样。
        start = random.randint(1990, 2035)
        for p in timeline(c, from_year=start, years=20):
            years.append(p["score"])
    stats = {k: [round(statistics.mean([r[k] for r in dims]), 2),
                 round(statistics.pstdev([r[k] for r in dims]), 2)]
             for k in scoring.DIMS}
    return sorted(vals), stats, sorted(years)


def _quantiles(sorted_vals):
    q = []
    for i in range(101):
        idx = min(len(sorted_vals) - 1, int(round(i / 100 * (len(sorted_vals) - 1))))
        q.append(round(sorted_vals[idx], 2))
    return q


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
    vals, stats, years = sample(n)
    q = _quantiles(vals)
    yq = _quantiles(years)
    body = (
        '"""Auto-generated by tools/make_percentiles.py — do not edit.\n\n'
        f'Sample: {n} random charts, seed 20261018.\n'
        f'overall mean={statistics.mean(vals):.2f} sd={statistics.pstdev(vals):.2f}\n'
        f'annual  mean={statistics.mean(years):.2f} sd={statistics.pstdev(years):.2f} '
        f'(n={len(years)})\n"""\n\n'
        "DIM_STATS = {\n"
    )
    for k in scoring.DIMS:
        body += f'    "{k}": {stats[k]},\n'
    body += "}\n\nQUANTILES = [\n"
    for i in range(0, 101, 10):
        body += "    " + ", ".join(f"{v:.2f}" for v in q[i:i + 10]) + ",\n"
    body += "]\n\nYEAR_QUANTILES = [\n"
    for i in range(0, 101, 10):
        body += "    " + ", ".join(f"{v:.2f}" for v in yq[i:i + 10]) + ",\n"
    body += "]\n"
    with open(os.path.join(ROOT, "mingli", "data_percentiles.py"), "w",
              encoding="utf-8") as f:
        f.write(body)
    print(f"n={n} overall mean={statistics.mean(vals):.2f} sd={statistics.pstdev(vals):.2f}")
    print(f"annual  n={len(years)} mean={statistics.mean(years):.2f} "
          f"sd={statistics.pstdev(years):.2f}")
    print("overall p10/p50/p90 =", q[10], q[50], q[90])
    print("annual  p10/p50/p90 =", yq[10], yq[50], yq[90])
    print("dim stats:", stats)
    os.system(f'PYTHONPATH="{ROOT}" {sys.executable} "{os.path.join(ROOT, "tools", "gen_js_data.py")}"')


if __name__ == "__main__":
    main()
