def _find(zhis, target: str) -> list[str]:
    """`target` may list several acceptable branches, e.g. '丑未'."""
    return [POS[i] for i, z in enumerate(zhis) if z in target]


def _find_any(ganzhi_pairs, chars: str) -> tuple[list[str], list[str]]:
    """Return (branch hits, stem hits)."""
    br, st = [], []
    for pos, (g, z) in zip(POS, ganzhi_pairs):
        if z in chars:
            br.append(pos)
        if g in chars:
            st.append(pos)
    return br, st


def compute(chart) -> dict:
    """Return {name: {nature, desc, positions, basis}} for every star present."""
    dm = chart.day_master
    pairs = [(p.gan, p.zhi) for p in chart.pillars]
    zhis = [p.zhi for p in chart.pillars]
    gans = [p.gan for p in chart.pillars]
    yz, dz, mz = chart.year.zhi, chart.day.zhi, chart.month.zhi
    out: dict[str, dict] = {}

    def put(name: str, positions: list[str], basis: str):
        if not positions:
            return
        nature, desc = DEFS[name]
        e = out.setdefault(name, {"nature": nature, "desc": desc,
                                  "positions": [], "basis": basis})
        for p in positions:
            if p not in e["positions"]:
                e["positions"].append(p)

    # 日干系
    for name, table, basis in (
            ("天乙贵人", TIANYI, f"日干{dm}查天乙"),
            ("太极贵人", TAIJI, f"日干{dm}查太极"),
            ("文昌贵人", WENCHANG, f"日干{dm}查文昌"),
            ("国印贵人", GUOYIN, f"日干{dm}查国印"),
            ("福星贵人", FUXING, f"日干{dm}查福星"),
            ("金舆", JINYU, f"日干{dm}查金舆"),
            ("红艳", HONGYAN, f"日干{dm}查红艳"),
            ("流霞", LIUXIA, f"日干{dm}查流霞"),
            ("学堂", XUETANG, f"日干{dm}长生之位"),
            ("禄神", LU, f"日干{dm}临官之位"),
            ("羊刃", YANGREN, f"日干{dm}帝旺之位")):
        put(name, _find(zhis, table[dm]), basis)

    # 三合系（年支、日支双查）
    for name, table, basis in (
            ("驿马", YIMA, "年支/日支三合局查驿马"),
            ("桃花", TAOHUA, "年支/日支三合局查桃花"),
            ("华盖", HUAGAI, "年支/日支三合局查华盖"),
            ("将星", JIANGXING, "年支/日支三合局查将星"),
            ("劫煞", JIESHA, "年支/日支三合局查劫煞"),
            ("灾煞", ZAISHA, "年支/日支三合局查灾煞"),
            ("亡神", WANGSHEN, "年支/日支三合局查亡神")):
        hits = []
        for src in (yz, dz):
            hits += _find(zhis, table[src])
        put(name, hits, basis)

    # 年支系
    hong = (3 - ZHI.index(yz)) % 12
    put("红鸾", _find(zhis, ZHI[hong]), f"年支{yz}查红鸾（卯上起子年逆数）")
    put("天喜", _find(zhis, ZHI[(hong + 6) % 12]), "红鸾对宫为天喜")
    put("孤辰", _find(zhis, GUSHEN[yz]), f"年支{yz}查孤辰")
    put("寡宿", _find(zhis, GUASU[yz]), f"年支{yz}查寡宿")
    put("破碎", _find(zhis, POSUI[yz]), f"年支{yz}查破碎")
    put("蜚廉", _find(zhis, FEILIAN[yz]), f"年支{yz}查蜚廉")

    # 月支系
    td = TIANDE[mz]
    br_hit, st_hit = _find_any(pairs, td)
    put("天德贵人", br_hit + st_hit, f"月支{mz}查天德（{td}）")
    md = YUEDE[mz]
    br_hit, st_hit = _find_any(pairs, md)
    put("月德贵人", br_hit + st_hit, f"月支{mz}查月德（{md}）")
    tianyi_branch = ZHI[(ZHI.index(mz) - 1) % 12]
    put("天医", _find(zhis, tianyi_branch), f"月支{mz}前一位为天医")

    season = next(k for k in TIANSHU_HIT if mz in k)
    sg, sz = TIANSHU_HIT[season]
    if chart.day.gan == sg and chart.day.zhi == sz:
        put("天赦", ["日"], f"{mz}月天赦在{sg}{sz}日")
    s1, s2 = SIFEI[season]
    if chart.day.gan + chart.day.zhi in (s1, s2):
        put("四废", ["日"], f"{mz}月四废日")

    # 日柱系
    gz = chart.day.gan + chart.day.zhi
    if gz in KUIGANG:
        put("魁罡", ["日"], "魁罡四日之一")
    if gz in SHIE_DABAI:
        put("十恶大败", ["日"], "十恶大败日")
    if gz in YINYANG_CUO:
        put("阴阳差错", ["日"], "阴阳差错日")
    put("空亡", [POS[i] for i, p in enumerate(chart.pillars) if p.zhi in p.kong],
        "按日柱旬空")

    # 新增：日干系续
    put("天官贵人", _find(zhis, TIANGUAN[dm]), f"日干{dm}查天官")
    put("天厨贵人", _find(zhis, TIANCHU[dm]), f"日干{dm}查天厨")
