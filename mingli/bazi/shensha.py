def _find(zhis, target: str) -> list[str]:
    """`target` may list several acceptable branches, e.g. '丑未'."""
    return [POS[i] for i, z in enumerate(zhis) if z in target]


def _find_any(ganzhi_pairs, chars: str) -> tuple[list[str], list[str]]:
    """Return (branch hits, stem hits)."""
    br, st = [], []
    for pos, (g, z) in zip(POS, ganzhi_pairs):
        if z in chars:
            br.append(pos)
        if g in chars:
            st.append(pos)
    return br, st


def compute(chart) -> dict:
    """Return {name: {nature, desc, positions, basis}} for every star present."""
    dm = chart.day_master
    pairs = [(p.gan, p.zhi) for p in chart.pillars]
    zhis = [p.zhi for p in chart.pillars]
    gans = [p.gan for p in chart.pillars]
    yz, dz, mz = chart.year.zhi, chart.day.zhi, chart.month.zhi
    out: dict[str, dict] = {}

    def put(name: str, positions: list[str], basis: str):
        if not positions:
            return
        nature, desc = DEFS[name]
        e = out.setdefault(name, {"nature": nature, "desc": desc,
                                  "positions": [], "basis": basis})
        for p in positions:
            if p not in e["positions"]:
                e["positions"].append(p)

    # 日干系：年干与日干双查。
    # 古法口诀「以年干或日干起贵人」——只查日干会漏掉一半，例如年干癸日干丙者，
    # 金舆在癸为寅、在丙为未，两种查法都要算，basis 里注明是哪一干查出来的。
    yg = chart.year.gan
    for name, table, label in (
            ("天乙贵人", TIANYI, "查天乙"),
            ("太极贵人", TAIJI, "查太极"),
            ("文昌贵人", WENCHANG, "查文昌"),
            ("国印贵人", GUOYIN, "查国印"),
            ("福星贵人", FUXING, "查福星"),
            ("金舆", JINYU, "查金舆"),
            ("红艳", HONGYAN, "查红艳"),
            ("流霞", LIUXIA, "查流霞"),
            ("学堂", XUETANG, "长生之位"),
            ("禄神", LU, "临官之位"),
            ("羊刃", YANGREN, "帝旺之位")):
        hits = _find(zhis, table[dm])
        basis = f"日干{dm}{label}"
        if yg != dm:
            more = _find(zhis, table[yg])
            if more:
                hits = hits + more
                basis += f"；年干{yg}{label}"
        put(name, hits, basis)

    # 三合系（年支、日支双查）
    for name, table, basis in (
            ("驿马", YIMA, "年支/日支三合局查驿马"),
            ("桃花", TAOHUA, "年支/日支三合局查桃花"),
            ("华盖", HUAGAI, "年支/日支三合局查华盖"),
            ("将星", JIANGXING, "年支/日支三合局查将星"),
            ("劫煞", JIESHA, "年支/日支三合局查劫煞"),
            ("灾煞", ZAISHA, "年支/日支三合局查灾煞"),
            ("亡神", WANGSHEN, "年支/日支三合局查亡神")):
        hits = []
        for src in (yz, dz):
            hits += _find(zhis, table[src])
        put(name, hits, basis)

    # 年支系
    hong = (3 - ZHI.index(yz)) % 12
    put("红鸾", _find(zhis, ZHI[hong]), f"年支{yz}查红鸾（卯上起子年逆数）")
    put("天喜", _find(zhis, ZHI[(hong + 6) % 12]), "红鸾对宫为天喜")
    put("孤辰", _find(zhis, GUSHEN[yz]), f"年支{yz}查孤辰")
    put("寡宿", _find(zhis, GUASU[yz]), f"年支{yz}查寡宿")
    put("破碎", _find(zhis, POSUI[yz]), f"年支{yz}查破碎")
    put("蜚廉", _find(zhis, FEILIAN[yz]), f"年支{yz}查蜚廉")

    # 年支系（续）：元辰与勾绞要分「阳男阴女 / 阴男阳女」。
    # 这是这类神煞里唯一依赖性别的两张表，所以单独算，并在依据里写明走的是哪一支。
    g = str(getattr(chart, "gender", "male"))
    male = g in ("male", "m", "男", "M", "Male")
    yang_path = (yg in "甲丙戊庚壬") == male      # 阳男 或 阴女
    yi = ZHI.index(yz)
    yc = (YUANCHEN_YANG if yang_path else YUANCHEN_YIN)[yz]
    put("元辰", _find(zhis, yc),
        f"年支{yz}{'阳男阴女' if yang_path else '阴男阳女'}查元辰（{yc}）")
    if yang_path:
        gou, jiao = ZHI[(yi + 3) % 12], ZHI[(yi - 3) % 12]
    else:
        gou, jiao = ZHI[(yi - 3) % 12], ZHI[(yi + 3) % 12]
    put("勾绞", _find(zhis, gou + jiao), f"年支{yz}，勾{gou}绞{jiao}")
    put("六厄", _find(zhis, LIUE[yz]), f"年支{yz}三合死位为六厄")
    put("丧门", _find(zhis, ZHI[(yi + 2) % 12]), f"年支{yz}前二位为丧门")
    put("吊客", _find(zhis, ZHI[(yi - 2) % 12]), f"年支{yz}后二位为吊客")

    # 月支系
    td = TIANDE[mz]
    br_hit, st_hit = _find_any(pairs, td)
    put("天德贵人", br_hit + st_hit, f"月支{mz}查天德（{td}）")
    md = YUEDE[mz]
    br_hit, st_hit = _find_any(pairs, md)
    put("月德贵人", br_hit + st_hit, f"月支{mz}查月德（{md}）")
    tianyi_branch = ZHI[(ZHI.index(mz) - 1) % 12]
    put("天医", _find(zhis, tianyi_branch), f"月支{mz}前一位为天医")

    # 月令德气：德干透出为龙德，德秀俱透为德秀贵人
    de, xiu = DESHOW[mz]
    de_hit = [POS[i] for i, (g, _z) in enumerate(pairs) if g in de]
    xiu_hit = [POS[i] for i, (g, _z) in enumerate(pairs) if g in xiu]
    put("龙德", de_hit, f"月支{mz}德干{de}透出")
    if de_hit and xiu_hit:
        put("德秀贵人", de_hit + xiu_hit, f"月支{mz}德{de}、秀{xiu}俱透")

    season = next(k for k in TIANSHU_HIT if mz in k)
    sg, sz = TIANSHU_HIT[season]
    if chart.day.gan == sg and chart.day.zhi == sz:
        put("天赦", ["日"], f"{mz}月天赦在{sg}{sz}日")
    s1, s2 = SIFEI[season]
    if chart.day.gan + chart.day.zhi in (s1, s2):
        put("四废", ["日"], f"{mz}月四废日")

    # 日柱系
    gz = chart.day.gan + chart.day.zhi
    if gz in KUIGANG:
        put("魁罡", ["日"], "魁罡四日之一")
    if gz in SHIE_DABAI:
        put("十恶大败", ["日"], "十恶大败日")
    if gz in YINYANG_CUO:
        put("阴阳差错", ["日"], "阴阳差错日")
    put("空亡", [POS[i] for i, p in enumerate(chart.pillars) if p.zhi in p.kong],
        "按日柱旬空")

    # 新增：日干系续
    for nm, tb, lb in (("天官贵人", TIANGUAN, "查天官"), ("天厨贵人", TIANCHU, "查天厨")):
        hits = _find(zhis, tb[dm])
        basis = f"日干{dm}{lb}"
        if yg != dm:
            more = _find(zhis, tb[yg])
            if more:
                hits = hits + more
                basis += f"；年干{yg}{lb}"
        put(nm, hits, basis)
    blade = YANGREN[dm]
    put("飞刃", _find(zhis, ZHI[(ZHI.index(blade) + 6) % 12]),
        f"羊刃{blade}之冲为飞刃")

    # 天德合 / 月德合
    td = TIANDE[mz]
    td_he = GAN_HE_MAP[td] if td in GAN_HE_MAP else ZHI_HE_MAP.get(td, "")
    if td_he:
        br_hit, st_hit = _find_any(pairs, td_he)
        put("天德合", br_hit + st_hit, f"{mz}月天德为{td}，合之为{td_he}")
    md = YUEDE[mz]
    md_he = GAN_HE_MAP.get(md, "")
    if md_he:
        br_hit, st_hit = _find_any(pairs, md_he)
        put("月德合", br_hit + st_hit, f"{mz}月月德为{md}，合之为{md_he}")

    # 日柱系续
    if gz in JINSHEN:
        put("金神", ["日"], "金神三日之一（乙丑/己巳/癸酉）")
    if gz in LIUXIU:
        put("六秀日", ["日"], "六秀日")
    if gz in SHILING:
        put("十灵日", ["日"], "十灵日")
    if gz in GULUAN:
        put("孤鸾煞", ["日"], "孤鸾八日之一")
    if gz in RIDE:
        put("日德", ["日"], "日德五日之一")

    # 三奇
    for a, b, c, label in SANQI:
        if all(x in gans for x in (a, b, c)):
            put("三奇贵人", ["全局"], f"{label}（{a}{b}{c}）齐见")

    # 天罗地网
    sky = [z for z in zhis if z in ("戌", "亥")]
    net = [z for z in zhis if z in ("辰", "巳")]
    hits = []
    if len(sky) >= 2:
        hits += _find(zhis, "戌") + _find(zhis, "亥")
    if len(net) >= 2:
        hits += _find(zhis, "辰") + _find(zhis, "巳")
    put("天罗地网", sorted(set(hits), key=POS.index), "戌亥天罗 / 辰巳地网齐见")

    order = {"吉": 0, "中": 1, "凶": 2}
    return dict(sorted(out.items(), key=lambda kv: (order[kv[1]["nature"]],
                                                   -len(kv[1]["positions"]))))
